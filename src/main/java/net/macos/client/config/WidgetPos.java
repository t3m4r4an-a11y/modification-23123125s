package net.macos.client.config;

public class WidgetPos {

    public int x = 0;
    public int y = 0;
    public boolean enabled = true;

    public WidgetPos() {}

    public WidgetPos(int x, int y, boolean enabled) {
        this.x = x;
        this.y = y;
        this.enabled = enabled;
    }
}